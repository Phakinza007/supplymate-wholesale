#!/usr/bin/env node
// Writes docs/showcase-catalogue.sql — the hand-run script that loads the
// catalogue into a HOSTED demo project's SQL Editor. It is generated from the
// same src/demo/catalogue.data.json as the local seed and the product art, so
// the hosted storefront, the static showcase and `supabase db reset` cannot
// describe three different shops. Run with --check in lint.
//
// Two things live here rather than in the catalogue data, because they are
// presentation policy for the hosted demo and not facts about a product:
//   - the price ladders (percentages off each product's own base price)
//   - which products deliberately get no ladder
import { readFileSync, writeFileSync } from 'node:fs'

const DATA_PATH = 'src/demo/catalogue.data.json'
const OUT_PATH = 'docs/showcase-catalogue.sql'
const check = process.argv.includes('--check')

const catalogue = JSON.parse(readFileSync(DATA_PATH, 'utf8'))
const text = (value) => `'${String(value).replace(/'/g, "''")}'`
const productImagePath = (slug) => `/images/supplymate/products/${slug}.svg`

for (const product of catalogue.products) {
  if (!catalogue.categories.some((category) => category.slug === product.categorySlug)) {
    console.error(`${product.slug} names an unknown category: ${product.categorySlug}`)
    process.exit(1)
  }
}

// The last product of each category is left without a ladder on purpose: a
// catalogue where everything has tiers hides what the "มีราคาขั้นบันได" filter
// and the "ยังไม่มีขั้น" admin badge are for. Derived rather than listed, so a
// renamed slug cannot silently drop a product out of the policy.
const laddered = catalogue.products.filter((product) => {
  const inCategory = catalogue.products.filter((p) => p.categorySlug === product.categorySlug)
  return inCategory[inCategory.length - 1].slug !== product.slug
})
// A tier at or below the MOQ is unreachable and the trigger rejects it, so
// products with a larger minimum get a ladder that starts above it.
const lowMoq = laddered.filter((product) => product.minOrderQuantity <= 2)
const highMoq = laddered.filter((product) => product.minOrderQuantity > 2)

const slugList = (products, perLine = 3) => {
  const quoted = products.map((product) => text(product.slug))
  const lines = []
  for (let index = 0; index < quoted.length; index += perLine) {
    lines.push(`                 ${quoted.slice(index, index + perLine).join(',')}`)
  }
  return lines.join(',\n').trimStart()
}

const categoryRows = catalogue.categories
  .map(
    (category) =>
      `  (${text(category.slug)}, ${text(category.name)},\n` +
      `   ${text(category.description)}, ${category.sortOrder}, true)`,
  )
  .join(',\n')

const productRows = catalogue.products
  .map(
    (product) =>
      `  (${text(product.slug)}, ${text(product.name)},\n` +
      `   ${text(product.description)},\n` +
      `   ${product.price.toFixed(2)}, ${text(product.sku)}, ${product.stockQuantity}, ` +
      `${text(product.packageUnit)}, ${product.unitsPerPackage}, ${product.minOrderQuantity}, ` +
      `${product.sortOrder}, ${text(product.categorySlug)})`,
  )
  .join(',\n')

const imageRows = catalogue.products
  .map(
    (product) =>
      `  (${text(product.slug)}, ${text(productImagePath(product.slug))}, ${text(product.name)})`,
  )
  .join(',\n')

const skuList = (() => {
  const quoted = catalogue.products.map((product) => text(product.sku))
  const lines = []
  for (let index = 0; index < quoted.length; index += 4) {
    lines.push(`               ${quoted.slice(index, index + 4).join(',')}`)
  }
  return lines.join(',\n').trimStart()
})()

const sql = `-- Showcase catalogue for the hosted demo.
--
-- GENERATED by \`npm run generate:catalogue\` from src/demo/catalogue.data.json.
-- Do not edit by hand — edit the catalogue data and regenerate. \`npm run lint\`
-- fails if this file drifts from the data.
--
-- NOT a migration and NOT seed.sql. Run it by hand, once, in the Supabase SQL
-- Editor of a demo project. It exists because a visitor lands on /shop without
-- logging in, so whatever is in there IS the pitch — and the headline feature
-- (wholesale price ladders) is invisible unless products actually have tiers.
--
-- Safe to re-run: every insert is keyed on slug and updates instead of
-- duplicating.
--
-- What it does:
--   1. archives whatever is currently on the storefront rather than deleting
--      it, so existing orders keep pointing at real product rows
--   2. adds ${catalogue.categories.length} packaging categories
--   3. adds ${catalogue.products.length} products with pack sizes and minimums a wholesaler would
--      recognise, each pointing at the generated illustration the app ships in
--      public/images/supplymate/products/
--   4. gives most of them a price ladder, which is the whole point

begin;

-- 1. Clear the storefront without destroying history. \`archived\` hides a
--    product from /shop but leaves it readable from old orders.
update public.products set status = 'archived' where status <> 'archived';

-- 1b. products.sku is unique. An archived product still holding a SKU this
--     script is about to assign would block the insert, so release it — only
--     where it actually collides, and only on rows already off the storefront.
update public.products
   set sku = null
 where status = 'archived'
   and sku in (${skuList});

-- 2. Categories.
insert into public.categories (slug, name, description, sort_order, is_active) values
${categoryRows}
on conflict (slug) do update
  set name = excluded.name,
      description = excluded.description,
      sort_order = excluded.sort_order,
      is_active = true;

-- 2b. Retire any category this catalogue does not name. Archiving products
--     leaves their categories behind, and an empty category still shows up in
--     the storefront's filter and on the home page as a heading with nothing
--     under it. Deactivated, not deleted: archived products keep pointing at a
--     real row.
update public.categories
   set is_active = false
 where slug not in (${catalogue.categories.map((category) => text(category.slug)).join(', ')});

-- 3. Products. \`price\` is per package (per ลัง/แพ็ก/กล่อง/ม้วน) and excludes
--    VAT — the shop adds 7% at order time. \`is_active\` is never written here:
--    trg_products_sync_is_active derives it from status.
insert into public.products
  (slug, name, description, price, sku, stock_quantity, package_unit,
   units_per_package, min_order_quantity, sort_order, status, category_id)
select v.slug, v.name, v.description, v.price, v.sku, v.stock, v.unit,
       v.per_pack, v.moq, v.sort, 'active', c.id
from (values
${productRows}
) as v(slug, name, description, price, sku, stock, unit, per_pack, moq, sort, category_slug)
join public.categories c on c.slug = v.category_slug
on conflict (slug) do update
  set name = excluded.name, description = excluded.description, price = excluded.price,
      sku = excluded.sku, stock_quantity = excluded.stock_quantity,
      package_unit = excluded.package_unit, units_per_package = excluded.units_per_package,
      min_order_quantity = excluded.min_order_quantity, sort_order = excluded.sort_order,
      status = 'active', category_id = excluded.category_id;

-- 4. Product images. The paths are root-relative assets the app itself ships,
--    not storage objects — resolveImageUrl() passes a leading-slash path
--    through untouched. Cleared first so a re-run cannot stack duplicates:
--    product_images has no unique key to conflict on.
delete from public.product_images i
 using public.products p
 where p.id = i.product_id
   and p.slug in (${slugList(catalogue.products)});

insert into public.product_images (product_id, storage_path, alt, sort_order)
select p.id, v.storage_path, v.alt, 0
from (values
${imageRows}
) as v(slug, storage_path, alt)
join public.products p on p.slug = v.slug;

-- 5. Price ladders. Percentages rather than fixed amounts so every product's
--    ladder stays sensible against its own base price. The last product in
--    each category is left without one on purpose: a catalogue where
--    everything has tiers hides what the "มีราคาขั้นบันได" filter and the
--    "ยังไม่มีขั้น" admin badge are actually for.
delete from public.product_price_tiers t
 using public.products p
 where p.id = t.product_id;

insert into public.product_price_tiers (product_id, min_quantity, unit_price)
select p.id, s.min_qty, round(p.price * s.factor, 2)
from public.products p
join (values
  (5, 0.96), (10, 0.93), (20, 0.90), (50, 0.86), (100, 0.82)
) as s(min_qty, factor) on true
where p.slug in (${slugList(lowMoq)})
  and s.min_qty > p.min_order_quantity;

-- The higher-MOQ items get a ladder that starts above their own minimum,
-- because a tier at or below it is unreachable and the trigger rejects it.
insert into public.product_price_tiers (product_id, min_quantity, unit_price)
select p.id, s.min_qty, round(p.price * s.factor, 2)
from public.products p
join (values
  (12, 0.95), (24, 0.91), (60, 0.87), (120, 0.83)
) as s(min_qty, factor) on true
where p.slug in (${slugList(highMoq)})
  and s.min_qty > p.min_order_quantity;

commit;

-- What the storefront should look like afterwards.
select p.name,
       p.package_unit || ' · ' || p.units_per_package || ' ชิ้น' as pack,
       p.price,
       p.price_per_piece,
       count(distinct t.id) as tiers,
       count(distinct i.id) as images
  from public.products p
  left join public.product_price_tiers t on t.product_id = p.id
  left join public.product_images i on i.product_id = p.id
 where p.status = 'active'
 group by p.id, p.name, p.package_unit, p.units_per_package, p.price, p.price_per_piece, p.sort_order
 order by p.sort_order;
`

const current = (() => {
  try {
    return readFileSync(OUT_PATH, 'utf8')
  } catch {
    return null
  }
})()

if (current === sql) {
  console.log(check ? 'hosted catalogue check OK' : `${OUT_PATH} is already up to date`)
  process.exit(0)
}

if (check) {
  console.error(
    `${OUT_PATH} is out of date with ${DATA_PATH}. Run \`npm run generate:catalogue\`.`,
  )
  process.exit(1)
}

writeFileSync(OUT_PATH, sql)
console.log(`wrote ${OUT_PATH} (${catalogue.products.length} products)`)
